fn main() {
    let data = [100, 200, 300, 400];
    let slice = &data[1..3]; // اسلایس شامل [200, 300] است

    // اندیس 2 در اسلایس معادل data[3] است که خارج از محدوده slice نیست!
    // اما اگر اندیس 2 را هم بدهیم مشکلی ندارد.
    // برای ایجاد خطا، اندیس بزرگتر از len-1 می‌دهیم:
    let value = slice[5]; // این خطا می‌دهد
    println!("{}", value);
}